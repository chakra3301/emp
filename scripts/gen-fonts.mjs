#!/usr/bin/env node
// packages/ui/fonts/*.woff2 → packages/ui/src/styles/fonts.css (licenses: packages/ui/FONTS-LICENSE.txt)
//
// JetBrains Mono (OFL) for code (see the license file).
// UI text and the wordmark use system fonts.
//
// Fonts are embedded as data: URLs because the Orion plugin sandbox allows `font-src data:` only.
// Families are namespaced ("EMP Mono") so they never collide with a host's own fonts.
// `--check` fails if the file is stale.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fonts = join(root, "packages/ui/fonts");
const out = join(root, "packages/ui/src/styles/fonts.css");

const face = (family, file, weight) => {
  const data = readFileSync(join(fonts, file)).toString("base64");
  const format = file.endsWith(".woff2") ? "woff2" : "woff";
  return `@font-face {
  font-family: "${family}";
  src: url(data:font/${format};base64,${data}) format("${format}");
  font-weight: ${weight};
  font-style: normal;
  font-display: swap;
}`;
};

const css = `/* Generated by scripts/gen-fonts.mjs. Licenses: packages/ui/FONTS-LICENSE.txt. Do not edit. */
${face("EMP Mono", "JetBrainsMono-Regular.woff2", 400)}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== css) {
    console.error("fonts.css is out of date. Run: npm run fonts");
    process.exit(1);
  }
  console.log("fonts.css up to date");
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out} (${Math.round(css.length / 1024)} KiB)`);
}
