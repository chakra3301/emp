#!/usr/bin/env node
// design/tokens.json → packages/ui/src/styles/tokens.css
//
// Every token becomes `--emp-<group>-<name>` (kebab-case), scoped to `.emp-root`.
// Run after tokens.json changes and commit the output. `--check` fails if the file is stale.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "design/tokens.json");
const out = join(root, "packages/ui/src/styles/tokens.css");

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const tokens = JSON.parse(readFileSync(src, "utf8"));
const lines = [];
for (const [group, values] of Object.entries(tokens)) {
  if (group.startsWith("$") || typeof values !== "object" || values === null) continue;
  for (const [name, value] of Object.entries(values)) {
    if (name.startsWith("$")) continue;
    if (typeof value !== "string" && typeof value !== "number") {
      console.error(`tokens.json: ${group}.${name} must be a string or number`);
      process.exit(1);
    }
    lines.push(`  --emp-${kebab(group)}-${kebab(name)}: ${value};`);
  }
}

const css = `/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */
.emp-root {
${lines.join("\n")}
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== css) {
    console.error("tokens.css is out of date with design/tokens.json. Run: npm run tokens");
    process.exit(1);
  }
  console.log(`tokens.css up to date (${lines.length} tokens)`);
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out} (${lines.length} tokens)`);
}
